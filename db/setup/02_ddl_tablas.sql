-- ----------------------------------------------------------------------------
-- 1. CATÁLOGOS (4 tablas)
-- ----------------------------------------------------------------------------
CREATE TABLE municipio (
    id_municipio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR2(100) NOT NULL,
    departamento VARCHAR2(50)  NOT NULL,
    CONSTRAINT uk_municipio_nombre_depto UNIQUE (nombre, departamento)
) TABLESPACE SICAC_DATA;

CREATE TABLE combustible (
    id_combustible NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR2(15)  NOT NULL,
    nombre         VARCHAR2(60)  NOT NULL,
    octanaje       NUMBER(3),
    unidad_medida  VARCHAR2(15)  DEFAULT 'LITROS' NOT NULL,
    descripcion    VARCHAR2(250),
    estado         VARCHAR2(15)  DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT uk_combustible_codigo UNIQUE (codigo),
    CONSTRAINT ck_combustible_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
) TABLESPACE SICAC_DATA;

CREATE TABLE tipo_vehiculo (
    id_tipo_vehiculo     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR2(60)  NOT NULL,
    consumo_prom_diario  NUMBER(8,2)   NOT NULL,
    cargas_semana_normal NUMBER(3)     NOT NULL,
    volumen_max_diario   NUMBER(8,2)   NOT NULL,
    descripcion          VARCHAR2(250),
    CONSTRAINT uk_tipo_vehiculo_nombre UNIQUE (nombre),
    CONSTRAINT ck_tv_valores CHECK (consumo_prom_diario > 0 AND cargas_semana_normal > 0 AND volumen_max_diario > 0)
) TABLESPACE SICAC_DATA;

CREATE TABLE tipo_alerta (
    id_tipo_alerta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR2(15)  NOT NULL,
    nombre         VARCHAR2(80)  NOT NULL,
    descripcion    VARCHAR2(250),
    nivel_riesgo   VARCHAR2(15)  NOT NULL,
    CONSTRAINT uk_tipo_alerta_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_alerta_riesgo CHECK (nivel_riesgo IN ('BAJO', 'MEDIO', 'ALTO', 'CRITICO'))
) TABLESPACE SICAC_DATA;

-- ----------------------------------------------------------------------------
-- 2. ACTORES Y VEHÍCULOS (4 tablas)
-- ----------------------------------------------------------------------------
CREATE TABLE persona (
    id_persona       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci               VARCHAR2(20)  NOT NULL,
    complemento      VARCHAR2(5),
    expedido         VARCHAR2(5)   NOT NULL,
    nombres          VARCHAR2(100) NOT NULL,
    apellido_paterno VARCHAR2(80)  NOT NULL,
    apellido_materno VARCHAR2(80),
    fecha_nacimiento DATE          NOT NULL,
    telefono         VARCHAR2(20),
    email            VARCHAR2(120),
    direccion        VARCHAR2(200),
    id_municipio     NUMBER        NOT NULL,
    estado           VARCHAR2(15)  DEFAULT 'ACTIVO' NOT NULL,
    motivo_bloqueo   VARCHAR2(250),
    fecha_registro   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_persona_ci_comp UNIQUE (ci, complemento),
    CONSTRAINT ck_persona_estado CHECK (estado IN ('ACTIVO', 'BLOQUEADO', 'INACTIVO')),
    CONSTRAINT fk_persona_municipio FOREIGN KEY (id_municipio) REFERENCES municipio(id_municipio)
) TABLESPACE SICAC_DATA;

CREATE TABLE huella_digital (
    id_huella      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona     NUMBER        NOT NULL,
    dedo           VARCHAR2(20)  NOT NULL,
    plantilla_hash VARCHAR2(256) NOT NULL,
    algoritmo      VARCHAR2(30)  DEFAULT 'SHA-256' NOT NULL,
    calidad        NUMBER(3)     NOT NULL,
    fecha_registro DATE          DEFAULT SYSDATE NOT NULL,
    estado         VARCHAR2(15)  DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT uk_huella_plantilla UNIQUE (plantilla_hash),
    CONSTRAINT ck_huella_calidad CHECK (calidad BETWEEN 1 AND 100),
    CONSTRAINT ck_huella_estado CHECK (estado IN ('ACTIVA', 'REVOCADA')),
    CONSTRAINT fk_huella_persona FOREIGN KEY (id_persona) REFERENCES persona(id_persona)
) TABLESPACE SICAC_DATA;

-- Solo una huella activa por persona y dedo (RN-04)
CREATE UNIQUE INDEX uq_huella_activa_dedo 
    ON huella_digital (CASE WHEN estado = 'ACTIVA' THEN id_persona END, CASE WHEN estado = 'ACTIVA' THEN dedo END)
    TABLESPACE SICAC_DATA;

CREATE TABLE vehiculo (
    id_vehiculo      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa            VARCHAR2(15)  NOT NULL,
    codigo_rfid      VARCHAR2(50),
    nro_chasis       VARCHAR2(40)  NOT NULL,
    marca            VARCHAR2(50)  NOT NULL,
    modelo           VARCHAR2(50)  NOT NULL,
    anio             NUMBER(4)     NOT NULL,
    cilindrada       NUMBER(5)     NOT NULL,
    color            VARCHAR2(30),
    id_tipo_vehiculo NUMBER        NOT NULL,
    id_combustible   NUMBER        NOT NULL,
    capacidad_tanque NUMBER(8,2)   NOT NULL,
    uso              VARCHAR2(30)  DEFAULT 'PARTICULAR' NOT NULL,
    estado           VARCHAR2(15)  DEFAULT 'ACTIVO' NOT NULL,
    motivo_bloqueo   VARCHAR2(250),
    fecha_registro   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_vehiculo_placa UNIQUE (placa),
    CONSTRAINT uk_vehiculo_rfid UNIQUE (codigo_rfid),
    CONSTRAINT uk_vehiculo_chasis UNIQUE (nro_chasis),
    CONSTRAINT ck_vehiculo_tanque CHECK (capacidad_tanque > 0 AND cilindrada > 0),
    CONSTRAINT ck_vehiculo_estado CHECK (estado IN ('ACTIVO', 'BLOQUEADO', 'BAJA')),
    CONSTRAINT fk_vehiculo_tipo FOREIGN KEY (id_tipo_vehiculo) REFERENCES tipo_vehiculo(id_tipo_vehiculo),
    CONSTRAINT fk_vehiculo_combustible FOREIGN KEY (id_combustible) REFERENCES combustible(id_combustible)
) TABLESPACE SICAC_DATA;

CREATE TABLE propiedad_vehiculo (
    id_propiedad       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona         NUMBER        NOT NULL,
    id_vehiculo        NUMBER        NOT NULL,
    fecha_inicio       DATE          DEFAULT SYSDATE NOT NULL,
    fecha_fin          DATE,
    documento_respaldo VARCHAR2(100) NOT NULL,
    CONSTRAINT ck_propiedad_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT fk_propiedad_persona FOREIGN KEY (id_persona) REFERENCES persona(id_persona),
    CONSTRAINT fk_propiedad_vehiculo FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo)
) TABLESPACE SICAC_DATA;

-- Un vehículo solo puede tener un propietario vigente a la vez (RN-02)
CREATE UNIQUE INDEX uq_vehiculo_propietario_vigente 
    ON propiedad_vehiculo (CASE WHEN fecha_fin IS NULL THEN id_vehiculo END)
    TABLESPACE SICAC_DATA;

-- ----------------------------------------------------------------------------
-- 3. RED DE DISTRIBUCIÓN Y FUNCIONARIOS (4 tablas)
-- ----------------------------------------------------------------------------
CREATE TABLE estacion (
    id_estacion        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_anh         VARCHAR2(25)  NOT NULL,
    nombre             VARCHAR2(120) NOT NULL,
    razon_social       VARCHAR2(150) NOT NULL,
    nit                VARCHAR2(20)  NOT NULL,
    direccion          VARCHAR2(200) NOT NULL,
    id_municipio       NUMBER        NOT NULL,
    latitud            NUMBER(10,6)  NOT NULL,
    longitud           NUMBER(10,6)  NOT NULL,
    telefono           VARCHAR2(20),
    estado             VARCHAR2(15)  DEFAULT 'ACTIVA' NOT NULL,
    fecha_habilitacion DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_estacion_codigo_anh UNIQUE (codigo_anh),
    CONSTRAINT ck_estacion_estado CHECK (estado IN ('ACTIVA', 'SUSPENDIDA', 'CLAUSURADA')),
    CONSTRAINT fk_estacion_municipio FOREIGN KEY (id_municipio) REFERENCES municipio(id_municipio)
) TABLESPACE SICAC_DATA;

CREATE TABLE funcionario (
    id_funcionario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona     NUMBER        NOT NULL,
    usuario        VARCHAR2(40)  NOT NULL,
    clave_hash     VARCHAR2(256) NOT NULL,
    rol            VARCHAR2(20)  NOT NULL,
    institucion    VARCHAR2(60)  NOT NULL,
    cargo          VARCHAR2(80)  NOT NULL,
    id_estacion    NUMBER,
    estado         VARCHAR2(15)  DEFAULT 'ACTIVO' NOT NULL,
    fecha_alta     DATE          DEFAULT SYSDATE NOT NULL,
    fecha_baja     DATE,
    CONSTRAINT uk_funcionario_usuario UNIQUE (usuario),
    CONSTRAINT ck_funcionario_rol CHECK (rol IN ('ADMIN', 'OPERADOR', 'FISCALIZADOR', 'ANALISTA', 'AUDITOR')),
    CONSTRAINT ck_funcionario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO')),
    CONSTRAINT fk_funcionario_persona FOREIGN KEY (id_persona) REFERENCES persona(id_persona),
    CONSTRAINT fk_funcionario_estacion FOREIGN KEY (id_estacion) REFERENCES estacion(id_estacion)
) TABLESPACE SICAC_DATA;

CREATE TABLE surtidor (
    id_surtidor       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion       NUMBER       NOT NULL,
    numero            NUMBER(3)    NOT NULL,
    lado              VARCHAR2(10) NOT NULL,
    id_combustible    NUMBER       NOT NULL,
    nro_serie         VARCHAR2(40) NOT NULL,
    estado            VARCHAR2(15) DEFAULT 'OPERATIVO' NOT NULL,
    fecha_instalacion DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_surtidor_est_num_lado UNIQUE (id_estacion, numero, lado),
    CONSTRAINT uk_surtidor_serie UNIQUE (nro_serie),
    CONSTRAINT ck_surtidor_estado CHECK (estado IN ('OPERATIVO', 'MANTENIMIENTO', 'FUERA_SERVICIO')),
    CONSTRAINT fk_surtidor_estacion FOREIGN KEY (id_estacion) REFERENCES estacion(id_estacion),
    CONSTRAINT fk_surtidor_combustible FOREIGN KEY (id_combustible) REFERENCES combustible(id_combustible)
) TABLESPACE SICAC_DATA;

CREATE TABLE recepcion_combustible (
    id_recepcion    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion     NUMBER       NOT NULL,
    id_combustible  NUMBER       NOT NULL,
    fecha_hora      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    cantidad_litros NUMBER(12,2) NOT NULL,
    nro_guia        VARCHAR2(40) NOT NULL,
    placa_cisterna  VARCHAR2(15) NOT NULL,
    tipo_registro   VARCHAR2(20) DEFAULT 'RECEPCION' NOT NULL, -- 'SALDO_INICIAL', 'RECEPCION', 'CONTEO_FISICO'
    CONSTRAINT uk_recepcion_guia UNIQUE (nro_guia),
    CONSTRAINT ck_recepcion_cantidad CHECK (cantidad_litros >= 0),
    CONSTRAINT ck_recepcion_tipo CHECK (tipo_registro IN ('SALDO_INICIAL', 'RECEPCION', 'CONTEO_FISICO')),
    CONSTRAINT fk_recepcion_estacion FOREIGN KEY (id_estacion) REFERENCES estacion(id_estacion),
    CONSTRAINT fk_recepcion_combustible FOREIGN KEY (id_combustible) REFERENCES combustible(id_combustible)
) TABLESPACE SICAC_DATA;

-- ----------------------------------------------------------------------------
-- 4. SUBVENCIÓN Y OPERACIÓN DE CARGA (2 tablas)
-- ----------------------------------------------------------------------------
CREATE TABLE subvencion_combustible (
    id_subvencion        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_combustible       NUMBER       NOT NULL,
    fecha_inicio         DATE         NOT NULL,
    fecha_fin            DATE,
    segmento             VARCHAR2(30) DEFAULT 'GENERAL' NOT NULL,
    precio_internacional NUMBER(8,2)  NOT NULL,
    precio_venta         NUMBER(8,2)  NOT NULL,
    monto_subvencion     NUMBER(8,2)  GENERATED ALWAYS AS (precio_internacional - precio_venta) VIRTUAL,
    cupo_mensual_litros  NUMBER(10,2),
    decreto_referencia   VARCHAR2(50) NOT NULL,
    fecha_registro       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_subv_comb_seg_inicio UNIQUE (id_combustible, segmento, fecha_inicio),
    CONSTRAINT ck_subv_precios CHECK (precio_internacional >= precio_venta AND precio_venta > 0),
    CONSTRAINT fk_subvencion_combustible FOREIGN KEY (id_combustible) REFERENCES combustible(id_combustible)
) TABLESPACE SICAC_DATA;

CREATE TABLE carga (
    id_carga            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo         NUMBER        NOT NULL,
    id_persona          NUMBER        NOT NULL,
    id_surtidor         NUMBER        NOT NULL,
    id_subvencion       NUMBER        NOT NULL,
    id_funcionario      NUMBER        NOT NULL,
    fecha_hora          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    cantidad_litros     NUMBER(10,2)  NOT NULL,
    metodo_verificacion VARCHAR2(15)  NOT NULL,
    nro_factura         VARCHAR2(40)  NOT NULL,
    estado              VARCHAR2(15)  DEFAULT 'VALIDA' NOT NULL,
    motivo_anulacion    VARCHAR2(250),
    CONSTRAINT ck_carga_cantidad CHECK (cantidad_litros > 0),
    CONSTRAINT ck_carga_metodo CHECK (metodo_verificacion IN ('HUELLA', 'RFID', 'MANUAL')),
    CONSTRAINT ck_carga_estado CHECK (estado IN ('VALIDA', 'ANULADA')),
    CONSTRAINT fk_carga_vehiculo FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo),
    CONSTRAINT fk_carga_persona FOREIGN KEY (id_persona) REFERENCES persona(id_persona),
    CONSTRAINT fk_carga_surtidor FOREIGN KEY (id_surtidor) REFERENCES surtidor(id_surtidor),
    CONSTRAINT fk_carga_subvencion FOREIGN KEY (id_subvencion) REFERENCES subvencion_combustible(id_subvencion),
    CONSTRAINT fk_carga_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario(id_funcionario)
) TABLESPACE SICAC_DATA;

-- ----------------------------------------------------------------------------
-- 5. CONTROL, ALERTAS Y AUDITORÍA (3 tablas)
-- ----------------------------------------------------------------------------
CREATE TABLE regla_deteccion (
    id_regla         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR2(15)  NOT NULL,
    nombre           VARCHAR2(100) NOT NULL,
    descripcion      VARCHAR2(300),
    id_tipo_alerta   NUMBER        NOT NULL,
    id_tipo_vehiculo NUMBER,
    ambito           VARCHAR2(15)  DEFAULT 'VEHICULO' NOT NULL,
    parametro        VARCHAR2(30)  NOT NULL,
    valor_umbral     NUMBER(10,2)  NOT NULL,
    ventana_horas    NUMBER(5)     NOT NULL,
    margen_error_pct NUMBER(5,2)   DEFAULT 0 NOT NULL,
    prioridad        NUMBER(2)     DEFAULT 1 NOT NULL,
    activa           CHAR(1)       DEFAULT 'S' NOT NULL,
    fecha_inicio     DATE          DEFAULT SYSDATE NOT NULL,
    fecha_fin        DATE,
    CONSTRAINT uk_regla_codigo UNIQUE (codigo),
    CONSTRAINT ck_regla_ambito CHECK (ambito IN ('VEHICULO', 'PROPIETARIO')),
    CONSTRAINT ck_regla_activa CHECK (activa IN ('S', 'N')),
    CONSTRAINT fk_regla_tipo_alerta FOREIGN KEY (id_tipo_alerta) REFERENCES tipo_alerta(id_tipo_alerta),
    CONSTRAINT fk_regla_tipo_vehiculo FOREIGN KEY (id_tipo_vehiculo) REFERENCES tipo_vehiculo(id_tipo_vehiculo)
) TABLESPACE SICAC_DATA;

CREATE TABLE alerta (
    id_alerta              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carga               NUMBER        NOT NULL,
    id_regla               NUMBER        NOT NULL,
    fecha_hora             TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    valor_detectado        NUMBER(10,2)  NOT NULL,
    valor_umbral           NUMBER(10,2)  NOT NULL,
    detalle                VARCHAR2(400) NOT NULL,
    estado                 VARCHAR2(15)  DEFAULT 'PENDIENTE' NOT NULL,
    id_funcionario_revisor NUMBER,
    fecha_revision         TIMESTAMP,
    observacion            VARCHAR2(400),
    CONSTRAINT uk_alerta_carga_regla UNIQUE (id_carga, id_regla),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'ATENDIDA', 'DESCARTADA')),
    CONSTRAINT ck_alerta_cierre CHECK (
        estado NOT IN ('ATENDIDA', 'DESCARTADA') OR 
        (id_funcionario_revisor IS NOT NULL AND fecha_revision IS NOT NULL AND observacion IS NOT NULL)
    ),
    CONSTRAINT fk_alerta_carga FOREIGN KEY (id_carga) REFERENCES carga(id_carga),
    CONSTRAINT fk_alerta_regla FOREIGN KEY (id_regla) REFERENCES regla_deteccion(id_regla),
    CONSTRAINT fk_alerta_revisor FOREIGN KEY (id_funcionario_revisor) REFERENCES funcionario(id_funcionario)
) TABLESPACE SICAC_DATA;

CREATE TABLE historial (
    id_historial   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_afectada VARCHAR2(50)   NOT NULL,
    id_registro    NUMBER         NOT NULL,
    operacion      VARCHAR2(10)   NOT NULL,
    columna        VARCHAR2(50),
    valor_anterior VARCHAR2(4000),
    valor_nuevo    VARCHAR2(4000),
    id_funcionario NUMBER,
    usuario_bd     VARCHAR2(50)   DEFAULT USER NOT NULL,
    ip_origen      VARCHAR2(45)   DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
    fecha_hora     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_historial_operacion CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT fk_historial_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario(id_funcionario)
) TABLESPACE SICAC_DATA;

-- ----------------------------------------------------------------------------
-- 6. ÍNDICES DE RENDIMIENTO (RNF-01, RNF-02)
-- ----------------------------------------------------------------------------
CREATE INDEX idx_carga_vehiculo_fecha ON carga (id_vehiculo, fecha_hora) TABLESPACE SICAC_DATA;
CREATE INDEX idx_carga_persona_fecha  ON carga (id_persona, fecha_hora)  TABLESPACE SICAC_DATA;
CREATE INDEX idx_carga_surtidor_fecha ON carga (id_surtidor, fecha_hora) TABLESPACE SICAC_DATA;
CREATE INDEX idx_propiedad_veh_vig    ON propiedad_vehiculo (id_vehiculo, fecha_fin) TABLESPACE SICAC_DATA;
CREATE INDEX idx_alerta_estado_fecha  ON alerta (estado, fecha_hora) TABLESPACE SICAC_DATA;
CREATE INDEX idx_historial_tabla_reg  ON historial (tabla_afectada, id_registro, fecha_hora) TABLESPACE SICAC_DATA;
